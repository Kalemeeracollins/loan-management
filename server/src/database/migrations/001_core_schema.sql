CREATE TABLE IF NOT EXISTS users (
  id CHAR(36) NOT NULL,
  name VARCHAR(120) NOT NULL,
  email VARCHAR(255) NOT NULL,
  phone VARCHAR(30) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  role ENUM('SUPER_ADMIN','LOAN_OFFICER','CREDIT_ANALYST','LOAN_APPROVER','FINANCE_OFFICER','AUDITOR','APPLICANT') NOT NULL DEFAULT 'APPLICANT',
  status ENUM('ACTIVE','INACTIVE','SUSPENDED') NOT NULL DEFAULT 'ACTIVE',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_users_email (email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS applicants (
  id CHAR(36) NOT NULL,
  type ENUM('INDIVIDUAL','BUSINESS') NOT NULL,
  full_name VARCHAR(200) NOT NULL,
  email VARCHAR(255) NOT NULL,
  phone VARCHAR(30) NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_applicants_email (email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS loan_products (
  id CHAR(36) NOT NULL,
  name VARCHAR(120) NOT NULL,
  description VARCHAR(500) NOT NULL,
  min_amount DECIMAL(19,4) NOT NULL,
  max_amount DECIMAL(19,4) NOT NULL,
  currency CHAR(3) NOT NULL,
  interest_rate DECIMAL(12,6) NOT NULL,
  interest_method ENUM('FLAT','REDUCING_BALANCE') NOT NULL,
  min_term_months INT NOT NULL,
  max_term_months INT NOT NULL,
  repayment_frequency ENUM('WEEKLY','BIWEEKLY','MONTHLY') NOT NULL,
  status ENUM('ACTIVE','INACTIVE','DRAFT') NOT NULL DEFAULT 'ACTIVE',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS loan_applications (
  id CHAR(36) NOT NULL,
  applicant_id CHAR(36) NOT NULL,
  product_id CHAR(36) NOT NULL,
  requested_amount DECIMAL(19,4) NOT NULL,
  term_months INT NOT NULL,
  purpose VARCHAR(500) NOT NULL,
  status ENUM('DRAFT','SUBMITTED','DOCUMENT_REVIEW','ASSESSMENT_PENDING','UNDER_REVIEW','MORE_INFORMATION_REQUIRED','APPROVED','REJECTED','AGREEMENT_PENDING','READY_FOR_DISBURSEMENT','DISBURSED','WITHDRAWN') NOT NULL DEFAULT 'SUBMITTED',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  KEY idx_applications_applicant_id (applicant_id),
  KEY idx_applications_status (status),
  KEY idx_applications_product_id (product_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS refresh_tokens (
  id CHAR(36) NOT NULL,
  user_id CHAR(36) NOT NULL,
  token_hash VARCHAR(255) NOT NULL,
  expires_at DATETIME(3) NOT NULL,
  revoked_at DATETIME(3) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  KEY idx_refresh_tokens_user_id (user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
